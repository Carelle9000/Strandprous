// Fonction pour obtenir la traduction
function getTranslation(key, language = 'en') {
  if (language === 'en') return key;
  return translations[key]?.[language] || key;
}

// Fonction pour appliquer les traductions à la page
function applyTranslations(language = 'fr') {
  document.querySelectorAll('[data-translate]').forEach(element => {
    const key = element.getAttribute('data-translate');
    const translation = getTranslation(key, language);
    
    if (element.tagName === 'INPUT' && element.type === 'text') {
      element.placeholder = translation;
    } else if (element.tagName === 'TEXTAREA') {
      element.placeholder = translation;
    } else if (element.tagName === 'OPTION') {
      element.textContent = translation;
    } else {
      // Vérifier si la traduction contient des balises HTML
      if (translation && translation.includes('<')) {
        element.innerHTML = translation;
      } else {
        element.textContent = translation;
      }
    }
  });
  
  // Appliquer les traductions aux placeholders
  document.querySelectorAll('[data-translate-placeholder]').forEach(element => {
    const key = element.getAttribute('data-translate-placeholder');
    const translation = getTranslation(key, language);
    element.placeholder = translation;
  });
  
  // Mettre à jour le titre de la page
  const titles = {
    'en': 'StrandPro — Salon Management Software | Kamel Tech Solutions LLC',
    'fr': 'StrandPro — Logiciel de Gestion de Salon | Kamel Tech Solutions LLC',
    'es': 'StrandPro — Software de Gestión de Salón | Kamel Tech Solutions LLC'
  };
  
  const descriptions = {
    'en': 'StrandPro — Salon management software for beauty salons, braiders, and stylists. Appointments, inventory, staff, payments, and revenue tracking. Operated by Kamel Tech Solutions LLC.',
    'fr': 'StrandPro — Logiciel de gestion de salon pour les salons de beauté, tresseuses et coiffeurs. Rendez-vous, inventaire, personnel, paiements et suivi des revenus. Exploité par Kamel Tech Solutions LLC.',
    'es': 'StrandPro — Software de gestión de salones para salones de belleza, trenzadoras y estilistas. Citas, inventario, personal, pagos y seguimiento de ingresos. Operado por Kamel Tech Solutions LLC.'
  };
  
  document.title = titles[language] || titles['en'];
  
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) {
    metaDesc.content = descriptions[language] || descriptions['en'];
  }
}

// Export pour utilisation dans d'autres fichiers
